const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const { bankStatistics } = require('../server/medical-library');
const context = { window: {}, document: { readyState: 'loading', addEventListener() {} }, console };
vm.runInNewContext(fs.readFileSync(require.resolve('./qbank-workspace.js'), 'utf8'), context);
const workspace = context.window.QBankWorkspace;
const items = [{id:1,subject:1,system:4},{id:1,subject:2,system:4},{id:2,subject:2,system:5},{id:3,subject:1,system:4}];
const draft = { subjects:['1','2'], systems:['4:1','4:2','5:2'], pools:['all'], ids:'', custom:false };
const stats = { progress:{1:'incorrect',2:'omitted'}, markedIds:[1] };
const facets=workspace.facets(items,{...draft,pools:['incorrect']},stats,true);
assert.equal(facets.ids.size,1);assert.equal(facets.subjects.get('1').size,1);assert.equal(facets.systems.get('4:2').size,1);
const timingDraft={timingBasis:'question',seconds:90,adjustment:0};
assert.equal(workspace.timing(timingDraft,40).total,3600);
assert.equal(workspace.timing({...timingDraft,adjustment:50},40).total,5400);
assert.equal(workspace.timing({...timingDraft,adjustment:-25},40).total,2700);
const divided=workspace.timing({timingBasis:'block',minutes:1},7);
assert.equal(divided.allocations.reduce((a,b)=>a+b,0),60);
assert.equal(Math.max(...divided.allocations)-Math.min(...divided.allocations),1);
assert.equal(workspace.timing(timingDraft,0).valid,false);
assert.equal(workspace.validateIds(items,'1,1,2').found,2);
assert.equal(workspace.validateIds(items,'999').valid,false);
const match = overrides => Array.from(workspace.matching(items,{...draft,...overrides},stats,true));
assert.deepEqual(match({}),[1,2,3]);
assert.deepEqual(match({subjects:['1'],systems:['4:2']}),[]);
assert.deepEqual(match({pools:['new']}),[3]);
assert.deepEqual(match({pools:['incorrect','omitted']}),[1,2]);
assert.deepEqual(match({pools:['marked']}),[1]);
assert.deepEqual(match({subjects:[]}),[]);
assert.deepEqual(match({custom:true,ids:'2, 999'}),[2]);
assert.deepEqual(match({custom:true,ids:'999'}),[]);
const q = (id,answer,tags) => ({source:{bank:'a',questionId:id}, submittedAnswer:answer, tags, _tutorMode:true});
const sessions = [{bank:'a',date:'2026-09-30',title:'First',id:'a',questions:[
  {...q(1,{submitted:true,isCorrect:true,selectedId:'1'},{subject:['A','B'],system:['Heart']}),starred:true,answerChanges:{I2C:1}},
  q(2,{submitted:true,isCorrect:false,selectedId:null},{subject:['A'],system:['Heart']})
]},{bank:'b',date:'2026-09-30',questions:[q(4,{submitted:true,isCorrect:true,selectedId:'1'},{subject:['C']})]}];
const result = bankStatistics(sessions,'a',10);
assert.equal(result.used,2); assert.equal(result.reports.subject.A.used,2); assert.equal(result.reports.subject.B.correct,1);
assert.equal(result.reports.system.Heart.omitted,1); assert.equal(result.changes.I2C,1);
assert.deepEqual(result.markedIds,[1]); assert.equal(result.tests.length,1); assert.equal(result.tests[0].score,50);
assert.equal(result.progress[2],'omitted');
const unfinished={bank:'a',date:'2026-10-01',questions:[{...q(3,{submitted:true,isCorrect:true,selectedId:'1'},{subject:['A']}),_tutorMode:false}]};
const withUnfinished=bankStatistics([...sessions,unfinished],'a',3);
assert.equal(withUnfinished.used,3,'Usage includes actual saved answers from ongoing tests');
assert.equal(withUnfinished.performance.used,2,'Performance excludes ongoing tests');
assert.equal(withUnfinished.tests.length,1,'Graphs only include completed tests');
console.log('PASS: multi-taxonomy intersections, deduplication, all/new/incorrect/marked/omitted pools, custom IDs, per-bank reports, answer changes and graph scores.');
const noteContext={window:{},TextEncoder,console};
vm.runInNewContext(fs.readFileSync(require.resolve('./dungeon-note.js'),'utf8'),noteContext);
const note=Object.create(noteContext.window.DungeonNote.prototype);
note.questionId='medos:step1:123';note.isSessionWide=false;
assert(!/[<>:"/\\|?*]/.test(note.noteId()),'Imported question note uses a Windows-safe filename');
const firstId=note.noteId();note.questionId='medos:step2:123';assert.notEqual(firstId,note.noteId(),'Banks keep different notes for the same numeric question ID');
console.log('PASS: persistent note IDs are Windows-safe and isolated by bank.');
